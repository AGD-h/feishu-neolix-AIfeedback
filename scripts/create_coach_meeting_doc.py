def get_tenant_access_token(app_id: str, app_secret: str) -> Optional[str]:
    """获取飞书访问令牌"""
    try:
        resp = SESSION.post(
            TOKEN_URL,
            json={"app_id": app_id, "app_secret": app_secret},
            timeout=30,
        )
        data = resp.json()
        if data.get("code") == 0:
            return data["tenant_access_token"]
        else:
            print(f"❌ 获取token失败: {data.get('msg')}")
            return None
    except Exception as e:
        print(f"❌ 获取token异常: {e}")
        return None


